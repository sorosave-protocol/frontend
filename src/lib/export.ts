/**
 * Download as PDF (opens print dialog)
 */
export function downloadPDF(html: string, filename: string): void {
  const blob = new Blob([html], { type: 'text/html' });
  const link = document.createElement('a');
  link.href = URL.createObjectURL(blob);
  link.download = filename.replace('.pdf', '.html');
  link.click();
  URL.revokeObjectURL(link.href);
  
  // Optionally trigger print dialog
  setTimeout(() => {
    window.print();
  }, 500);
}

/**
 * Main export function
 */
export async function exportGroupData(
  group: GroupSummary,
  contributions: ContributionRecord[],
  format: 'csv' | 'pdf'
): Promise<void> {
  const timestamp = new Date().toISOString().split('T')[0];
  const filename = `${group.name.replace(/\s+/g, '_')}_export_${timestamp}`;

  if (format === 'csv') {
    const csv = exportContributionsCSV(contributions, group.name);
    downloadCSV(csv, `${filename}.csv`);
  } else {
    const html = exportGroupSummaryPDF(group, contributions);
    downloadPDF(html, filename);
  }
}
