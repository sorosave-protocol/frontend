/**
 * Data Export Utilities
 * Export group data as CSV or PDF
 * Issue: #60
 */

export interface ContributionRecord {
  date: string;
  member: string;
  amount: string;
  round: number;
  status: 'pending' | 'completed';
}

export interface GroupSummary {
  name: string;
  id: number;
  createdAt: string;
  totalRounds: number;
  currentRound: number;
  totalContributed: string;
  members: string[];
  payouts: string[];
}

/**
 * Export contributions to CSV format
 */
export function exportContributionsCSV(contributions: ContributionRecord[], groupName: string): string {
  const headers = ['Date', 'Member', 'Amount', 'Round', 'Status'];
  const rows = contributions.map(c => [
    c.date,
    c.member,
    c.amount,
    c.round.toString(),
    c.status
  ]);

  const csvContent = [
    headers.join(','),
    ...rows.map(row => row.map(cell => `"${cell}"`).join(','))
  ].join('\n');

  return csvContent;
}

/**
 * Download CSV file
 */
export function downloadCSV(csvContent: string, filename: string): void {
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const link = document.createElement('a');
  link.href = URL.createObjectURL(blob);
  link.download = filename;
  link.click();
  URL.revokeObjectURL(link.href);
}

